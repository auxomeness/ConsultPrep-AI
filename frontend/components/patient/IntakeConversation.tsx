"use client";

import { useState } from "react";
import ConversationTurn from "./ConversationTurn";
import ResponseComposer from "./ResponseComposer";

const initialQuestion = "What would you like to discuss with a healthcare professional?";
const syntheticFollowUp = "When did this concern begin, and has it changed since then?";

export default function IntakeConversation() {
  const [initialDraft, setInitialDraft] = useState("");
  const [checkedResponse, setCheckedResponse] = useState<string | null>(null);
  const [followUpDraft, setFollowUpDraft] = useState("");

  function updateInitialDraft(value: string) {
    setInitialDraft(value);
    setCheckedResponse(null);
  }

  return (
    <section aria-labelledby="conversation-title" className="mt-10">
      <h2 id="conversation-title" className="text-xl font-semibold leading-8">
        Conversation preview
      </h2>
      <div className="mt-5 space-y-5">
        <ConversationTurn label="Initial intake question" text={initialQuestion} kind="question" />
        <ResponseComposer
          label="Your initial concern"
          instructions="Write in your own words. Use made-up information in this preview."
          placeholder="For example, I would like to discuss a concern that began this week."
          value={initialDraft}
          onChange={updateInitialDraft}
          onValidCheck={setCheckedResponse}
        />

        {checkedResponse !== null && (
          <>
            <ConversationTurn
              label="Your response · Local preview"
              text={checkedResponse}
              kind="response"
              description="Shown exactly as entered for this local preview."
            />
            <ConversationTurn
              label="Synthetic preview question"
              text={syntheticFollowUp}
              kind="question"
              description="A fixed question for testing this interface. It was not generated by AI or written by a clinician."
            />
            <ResponseComposer
              label="Your response to the synthetic preview question"
              instructions="Add a made-up response. This is an editable local draft; there is no next step in this preview."
              placeholder="For example, the made-up concern began this week."
              value={followUpDraft}
              onChange={setFollowUpDraft}
            />
          </>
        )}
      </div>
    </section>
  );
}
