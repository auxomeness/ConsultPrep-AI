import { fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it } from "vitest";
import IntakeConversation from "../../components/patient/IntakeConversation";

describe("IntakeConversation", () => {
  it("presents the exact locally checked wording before one synthetic follow-up", async () => {
    const user = userEvent.setup();
    render(<IntakeConversation />);
    const initial = screen.getByRole("textbox", { name: "Your initial concern" });
    const exactResponse = "  A made-up concern, in my own words.\nIt changed yesterday.  ";

    expect(screen.getByRole("article", { name: "Initial intake question" })).toBeTruthy();
    expect(screen.queryByRole("article", { name: "Synthetic preview question" })).toBeNull();
    fireEvent.change(initial, { target: { value: exactResponse } });
    await user.click(screen.getByRole("button", { name: "Check response locally" }));

    const patientTurn = screen.getByRole("article", { name: /Your response · Local preview/ });
    const followUp = screen.getByRole("article", { name: "Synthetic preview question" });
    expect(patientTurn.querySelector("p")?.textContent).toBe(exactResponse);
    expect(patientTurn.textContent).not.toMatch(/saved|submitted|clinician verified|AI generated/i);
    expect(followUp.textContent).toMatch(/When did this concern begin, and has it changed since then\?/);
    expect(followUp.textContent).toMatch(/not generated by AI or written by a clinician/i);
    expect(patientTurn.compareDocumentPosition(followUp) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
  });

  it("keeps the second response editable and retains it when the first concern is rechecked", async () => {
    const user = userEvent.setup();
    render(<IntakeConversation />);
    const initial = screen.getByRole("textbox", { name: "Your initial concern" });
    const check = screen.getByRole("button", { name: "Check response locally" });

    await user.type(initial, "A synthetic initial concern.");
    await user.click(check);
    const second = screen.getByRole("textbox", { name: "Your response to the synthetic preview question" }) as HTMLTextAreaElement;
    expect(second.getAttribute("aria-describedby")).toBeTruthy();
    await user.type(second, "A made-up second response.");
    expect(second.value).toBe("A made-up second response.");
    await user.type(second, " More detail.");
    expect(second.value).toBe("A made-up second response. More detail.");

    await user.type(initial, " Additional detail.");
    expect(screen.queryByRole("article", { name: "Synthetic preview question" })).toBeNull();
    await user.click(check);
    expect(screen.getByRole("article", { name: /Your response · Local preview/ }).querySelector("p")?.textContent).toBe(
      "A synthetic initial concern. Additional detail.",
    );
    expect(screen.getByRole("textbox", { name: "Your response to the synthetic preview question" })).toHaveProperty(
      "value",
      "A made-up second response. More detail.",
    );
    expect(screen.getAllByRole("button", { name: "Check response locally" })).toHaveLength(1);
    expect(screen.queryByRole("button", { name: /save|send|submit/i })).toBeNull();
  });
});
